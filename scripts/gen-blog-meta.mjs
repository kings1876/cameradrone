// Writes src/data/blogMeta.ts: every post without its body, so list pages and SEO metadata stay in the main bundle
// while article bodies load on demand. Run automatically before build.
import { build } from 'esbuild';
import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

const entry = 'scripts/.blogmeta-entry.ts';
const out = 'scripts/.blogmeta.bundle.mjs';
fs.writeFileSync(entry, "export { BLOG_POSTS } from '../src/data/blogPosts';\nexport { blockWords } from '../src/lib/richText';\n");
await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error' });
const mod = await import(pathToFileURL(path.resolve(out)).href);
const rows = mod.BLOG_POSTS.map(p => {
  const { content, ...rest } = p;
  const faq = content.flatMap(b => (typeof b === 'object' && 'faq' in b ? b.faq : []));
  return { ...rest, wordCount: mod.blockWords(content), faq };
}).sort((a, b) => b.dateISO.localeCompare(a.dateISO));
const body = "// GENERATED by scripts/gen-blog-meta.mjs from src/data/blogPosts.ts. Do not edit by hand.\nimport { BlogSummary } from '../types';\n\nexport const BLOG_SUMMARIES: BlogSummary[] = " + JSON.stringify(rows, null, 2) + ';\n';
fs.writeFileSync('src/data/blogMeta.ts', body);
fs.rmSync(entry, { force: true });
fs.rmSync(out, { force: true });
console.log('blogMeta.ts written:', rows.length, 'posts');
